def group_command_requires_enabled(
    command: str,
    private_account_commands: Iterable[str] = (),
) -> bool:
    return command not in (*GROUP_GATE_EXEMPT_COMMANDS, *tuple(private_account_commands))


def arena_base_command(command: str) -> str:
    text = str(command or "")
    if text.startswith(CHANNEL_PREFIX):
        candidate = text[len(CHANNEL_PREFIX):]
        if candidate in ARENA_CHANNEL_BASE_COMMANDS:
            return candidate
    return text


def arena_command_platform(command: str) -> str:
    text = str(command or "")
    if text.startswith(CHANNEL_PREFIX) and arena_base_command(text) != text:
        return ARENA_PLATFORM_CHANNEL
    return ARENA_PLATFORM_CHANNEL


def normalize_command_text(text: str, strip_leading_slash: bool = True) -> str:
    normalized = " ".join(str(text or "").strip().split())
    if strip_leading_slash and normalized.startswith("/"):
        return normalized[1:].lstrip()
    return normalized


def match_plain_command(text: str, commands: Iterable[str]) -> str | None:
    normalized = normalize_command_text(text, strip_leading_slash=False)
    for command in commands:
        if normalized == command or normalized.startswith(command + " "):
            return command
    return None


def should_dispatch_plain_text(
    text: str,
    commands: Iterable[str],
    is_at_or_wake_command: bool,
    already_processed: bool = False,
) -> bool:
    if already_processed or is_at_or_wake_command:
        return False
    return match_plain_command(text, commands) is not None
